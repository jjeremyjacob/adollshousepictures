function closePlayers() {
    if (activePlayer) {
        try {
            activePlayer.destroy();
        } catch (_) {}

        activePlayer = null;
    }

    activePlayers.forEach(player => {
        try {
            player.destroy();
        } catch (_) {}
    });

    activePlayers = [];
}


